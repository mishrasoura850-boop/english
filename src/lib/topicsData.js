export function getRandomTopic(excludeId = null) {
  const filtered = excludeId 
    ? SPEAKING_TOPICS.filter(t => t.id !== excludeId)
    : SPEAKING_TOPICS;
  const randomIndex = Math.floor(Math.random() * filtered.length);
  return filtered[randomIndex] || SPEAKING_TOPICS[0];
}

export function getTopicsByCategory(category) {
  if (!category || category === 'All') return SPEAKING_TOPICS;
  return SPEAKING_TOPICS.filter(t => t.category.toLowerCase() === category.toLowerCase());
}

export function getTopicsByDifficulty(difficulty) {
  if (!difficulty || difficulty === 'All') return SPEAKING_TOPICS;
  return SPEAKING_TOPICS.filter(t => t.difficulty.toLowerCase() === difficulty.toLowerCase());
}

